"""Run the English literature stage with real OpenRouter models under a persistent USD 2 reservation cap."""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path

import httpx

from airesearcher.core.models.common import ProjectState as S
from airesearcher.core.project import Project
from airesearcher.core.workspace import air_home
from airesearcher.engine.engine import ProjectEngine
from airesearcher.engine.stage import describe
from airesearcher.llm.gateway import LLMGateway
from airesearcher.llm.models import get_secret
from airesearcher.stages.idea.stage import IdeaStage

from .budgeted import RATES, BudgetedBackend


def model_config():
    models = {}
    for name, tier, maximum in (("gemini-2.5-flash", "fast", 4096), ("gemini-2.5-pro", "strong", 8192)):
        pin, pout = RATES[f"openrouter/google/{name}"]
        models[f"literature-{tier}"] = {
            "model": f"google/{name}", "api_base": "https://openrouter.ai/api/v1",
            "key_env": "OPENROUTER_API_KEY", "max_tokens": maximum, "price": [pin, pout],
            "params": {"timeout": 90, "num_retries": 0,
                       "extra_body": {"reasoning": {"max_tokens": 1024} if tier == "strong" else {"enabled": False}}},
            "description": f"Literature validation {tier} tier",
        }
    return {"models": models, "stages": {"idea": {"fast": "literature-fast", "strong": "literature-strong"}},
            "fallbacks": {"literature-fast": [], "literature-strong": []}}


def check_catalog():
    response = httpx.get("https://openrouter.ai/api/v1/models", timeout=30)
    response.raise_for_status()
    catalog = {row["id"]: row for row in response.json()["data"]}
    for name, rates in RATES.items():
        row = catalog.get(name.removeprefix("openrouter/"))
        if not row:
            raise RuntimeError("A selected validation model is unavailable; review the model configuration.")
        prices = row["pricing"]
        if float(prices["prompt"]) * 1_000_000 > rates[0] + 1e-6:
            raise RuntimeError("The selected model's input price increased; review the budget estimate.")
        if float(prices["completion"]) * 1_000_000 > rates[1] + 1e-6:
            raise RuntimeError("The selected model's output price increased; review the budget estimate.")




def repair_queries(project):
    """Replace incompatible LoRA demo queries while preserving the original archived plan."""
    if "lora" not in project.config.goal.casefold():
        raise ValueError("The deterministic query repair is limited to this LoRA workflow example.")
    from airesearcher.stages.idea.evidence import load_json
    from airesearcher.stages.idea.models import QueryPlan
    from airesearcher.stages.idea.storage import save_json

    prior = project.archive.latest("idea/queries.json")
    plan = QueryPlan.model_validate({"subquestions": [
        {"question": "LoRA methods", "purpose": "Find original low-rank adaptation literature", "queries": ["LoRA"]},
        {"question": "Parameter-efficient baselines", "purpose": "Find related adaptation approaches",
         "queries": ["parameter efficient fine tuning"]},
        {"question": "Few-sample evaluation", "purpose": "Find small-data fine-tuning settings",
         "queries": ["few sample BERT"]},
    ]})
    save_json(project, "idea/query_repair.json", {
        "reason": "The initial Boolean queries were incompatible with the cross-source keyword adapter.",
        "original_plan_ref": prior.model_dump(mode="json") if prior else None,
        "original_plan": load_json(project, "idea/queries.json") if prior else None,
        "replacement": plan.model_dump(mode="json"),
        "method": "Deterministic LoRA example queries; not generated by a new model call.",
    })
    save_json(project, "idea/queries.json", plan.model_dump(mode="json"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, required=True)
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--recover-from", type=Path, help="Replay paid reading replies from a prior validation")
    parser.add_argument("--repair-queries", action="store_true",
                        help="Repair incompatible LoRA queries in an existing retrieval run")
    parser.add_argument("--budget-ledger", type=Path, default=air_home() / "literature_validation_budget.json")
    parser.add_argument("--timeout", type=float, default=900)
    args = parser.parse_args()
    secret = get_secret("OPENROUTER_API_KEY")
    if not secret or len(secret.strip()) <= 1 or any(c.isspace() for c in secret):
        parser.error("A complete OPENROUTER_API_KEY must be configured locally; never paste it into logs.")
    # Availability and price metadata do not invoke model generation.
    check_catalog()
    if args.resume:
        project = Project.open(args.workspace)
        if project.config.models != model_config():
            parser.error("The project model configuration differs from this reviewed validation profile.")
        if project.config.budget["llm_usd"].hard != 2:
            parser.error("The validation project must retain the USD 2 budget cap.")
    else:
        if args.workspace.exists() and any(args.workspace.iterdir()):
            parser.error("Use an empty directory, or --resume for the same project and budget ledger.")
        project = Project.create(
            root=args.workspace, register=False, task="tasks/smoke",
            title="LoRA literature workflow validation",
            goal="Compare LoRA and full fine-tuning for low-resource text classification. "
                 "First validate the literature and idea workflow; do not claim that the smoke task can train LoRA.",
            constraints={"purpose": "Literature workflow validation only; no model training", "language": "English"},
            models=model_config(), budget={"llm_usd": {"soft": 1.5, "hard": 2}},
            limits={"search_papers": 6, "read_papers": 3, "reader_concurrency": 1},
            literature={"year_from": 2018}, llm_cache="record", dev={"stage_impl": {"idea": "real"}},
        )
    if args.recover_from:
        if args.resume:
            parser.error("Cache recovery requires a fresh empty workspace.")
        from .recovery import seed_cached_run
        seed_cached_run(project, args.recover_from)
    if args.repair_queries:
        if not args.resume:
            parser.error("Query repair requires --resume and the original budget ledger.")
    backend = BudgetedBackend(args.budget_ledger, cap=2)
    engine = ProjectEngine(project, llm=LLMGateway(project, backend=backend, backoff_base=0),
                           stages={"idea": IdeaStage()}, retry_delay=0)
    if args.repair_queries:
        if engine.state != S.IdeaDrafting or engine.ck.scratch.get("idea", {}).get("phase") != "search":
            parser.error("Query repair is allowed only during the retrieval phase, before screening and reading.")
        repair_queries(project)
    deadline = time.monotonic() + args.timeout
    while time.monotonic() < deadline:
        if engine.state != S.IdeaDrafting:
            break
        if any(c["status"] != "done" for c in backend.read()["calls"]):
            print("A prior request has unknown cost; manual usage review is required.", flush=True)
            break
        if project.config.llm_cache == "replay" and engine.ck.scratch.get("idea", {}).get("phase") == "gap":
            from airesearcher.stages.idea.evidence import load_json
            if load_json(engine.build_context(), "idea/reading_status.json")["failed"]:
                print("Cached reading recovery was incomplete; no new paid calls will be scheduled.", flush=True)
                break
            from .recovery import finish_replay
            finish_replay(project)
        if engine.ck.scratch.get("idea", {}).get("phase") == "refine":
            from airesearcher.stages.idea.evidence import load_json
            status = load_json(engine.build_context(), "idea/merge_status.json")
            if status["needs_human"]:
                print("Unresolved literature conflicts require human review before further paid requests.", flush=True)
                break
        if engine.ck.scratch.get("idea", {}).get("phase") == "screen":
            from airesearcher.services.literature import load_papers
            if not load_papers(project.root):
                print("No papers were retrieved; no further model calls will be scheduled.", flush=True)
                break
        tick = engine.tick()
        if tick.result is not None:
            print(describe(tick.result), flush=True)
        if tick.seconds:
            time.sleep(min(tick.seconds, 5, max(0, deadline - time.monotonic())))
    ledger = backend.read()
    report = {
        "state": engine.state.value, "phase": engine.ck.scratch.get("idea", {}).get("phase"),
        "project": str(project.root), "project_model_cost_estimate_usd": project.budget.used().get("llm_usd", 0),
        "cumulative_model_cost_estimate_usd": sum(c.get("measured_usd", 0) for c in ledger["calls"]),
        "budget_committed_usd": backend.committed(ledger), "cap_usd": 2,
        "calls_in_ledger": len(ledger["calls"]),
        "unknown_cost_calls": sum(c["status"] != "done" for c in ledger["calls"]),
        "note": "Reservations are conservative estimates. Provider-side limits remain authoritative.",
    }
    print(json.dumps(report, indent=2), flush=True)
    if engine.state != S.IdeaPending:
        raise SystemExit("Validation stopped before approval. Inspect its state and receipts before further requests.")


if __name__ == "__main__":
    main()
