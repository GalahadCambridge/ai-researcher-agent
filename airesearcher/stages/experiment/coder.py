"""Restricted coding tools, semantic guard and preflight (§7).

The engine runs a coding session in a worker thread and returns Wait while its
bounded trial is active. No general shell, package installer or network tool.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from copy import copy
from pathlib import Path

from pydantic import BaseModel, ConfigDict

from airesearcher.core.fsutil import dumps, sha256_bytes
from airesearcher.llm.gateway import LiteLLMBackend, tool


class _BudgetCheckedBackend(LiteLLMBackend):
    """Use the existing budget before another tool-loop request; accounting stays in the gateway."""

    def __init__(self, backend, budget):
        self.backend = backend
        self.budget = budget

    def call(self, request):
        if self.budget.check().exhausted:
            raise ValueError("Budget exhausted before the next LLM request")
        return self.backend.call(request)


class CoderReport(BaseModel):
    model_config = ConfigDict(extra="forbid")
    ok: bool
    changed_files: list[str]
    summary: str
    trial_run_id: str | None
    needs_plan_change: bool
    plan_change_reason: str = ""


class CoderRollbackRequired(RuntimeError):
    """Carry the session snapshot to the engine if worker-side cleanup cannot run."""

    def __init__(self, before, cause):
        super().__init__(str(cause) or type(cause).__name__)
        self.before = before


def snapshot(root):
    return {
        p.relative_to(root).as_posix(): p.read_bytes()
        for folder in ("src", "configs")
        for p in (root / folder).rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }


def restore(ctx, before, commit=None):
    current = snapshot(ctx.root)
    for name in current.keys() - before.keys():
        (ctx.root / name).unlink()
    for name, value in before.items():
        p = ctx.root / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(value)
    # An explicit rollback commit preserves both the attempted edit and reversal.
    commit = commit or ctx.workspace.commit
    return commit("Revert rejected coder changes", author="agent:experiment")


def semantic_guard(ctx, task, entries, before, report):
    problems = []
    after = snapshot(ctx.root)
    for name in task.protected_files:
        path = "src/" + name
        if path not in before or after.get(path) != before[path]:
            problems.append("Protected file changed: " + path)
    for key, entry in entries.items():
        path = ctx.root / "configs" / entry["experiment_id"] / (key + ".yaml")
        import yaml

        text = path.read_text(encoding="utf-8")
        try:
            cfg = json.loads(text)
        except json.JSONDecodeError:
            cfg = yaml.safe_load(text)
        if not isinstance(cfg, dict) or any(cfg.get(k) != entry["config"].get(k) for k in task.semantic_keys):
            problems.append("Experiment semantics changed: " + key)
        # Configurations are generated by deterministic code, not rewritten by the model.
        if cfg != entry["config"]:
            problems.append("Generated configuration was edited: " + key)
    if report.needs_plan_change:
        problems.append("A plan change is required: " + report.plan_change_reason)
    return problems


def run_coder(ctx, approved, experiment, entries, run_trial, error="", commit=None, dispatch=None):
    commit = commit or ctx.workspace.commit
    dispatch = dispatch or (lambda action: action())
    before = snapshot(ctx.root)
    changed, trials = set(), []
    task = approved.task

    def resolve(path, write=False):
        p = Path(path)
        p = (ctx.root / p).resolve() if not p.is_absolute() else p.resolve()
        roots = [ctx.root / "src", ctx.root / "configs"]
        if not write:
            roots.append(approved.task_dir)
        if not any(p == r.resolve() or r.resolve() in p.parents for r in roots):
            raise ValueError("Path outside permitted task/code/configuration directories")
        if write:
            if any(p == (ctx.root / "src" / name).resolve() for name in task.protected_files):
                raise ValueError("Protected file cannot be edited")
            ctx.permissions.guard("write", str(p), actor="agent:exp.coder")
        return p

    @tool()
    def list_files(dir: str) -> list[str]:
        """List permitted source/config/current-task files."""
        base = resolve(dir)
        return [str(p.relative_to(base)) for p in sorted(base.rglob("*")) if p.is_file()][:500]

    @tool()
    def read_file(path: str, start_line: int = 1, end_line: int = 200) -> str:
        """Read at most 300 lines from an allowed file."""
        if start_line < 1 or not start_line <= end_line < start_line + 300:
            raise ValueError("Invalid line range")
        return "\n".join(resolve(path).read_text(encoding="utf-8").splitlines()[start_line - 1 : end_line])

    @tool(action="write", target="path")
    def write_file(path: str, content: str) -> str:
        """Write source/config only, excluding protected files."""
        p = resolve(path, True)
        if len(content) > 500_000:
            raise ValueError("File exceeds session size limit")

        def write():
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")

        dispatch(write)
        changed.add(p.relative_to(ctx.root).as_posix())
        return "written"

    @tool(action="write", target="path")
    def replace_in_file(path: str, old: str, new: str) -> str:
        """Replace a unique literal occurrence in an allowed file."""
        text = resolve(path, True).read_text(encoding="utf-8")
        if not old or text.count(old) != 1:
            raise ValueError("The old text must occur exactly once")
        return write_file(path, text.replace(old, new))

    @tool(action="exec")
    def trial(task_key: str) -> dict:
        """Run a fixed-entrypoint trial, at most four per coding session."""
        if len(trials) >= 4:
            raise ValueError("Maximum four trials per session")
        if task_key not in entries or entries[task_key]["experiment_id"] != experiment.id:
            raise ValueError("Task is not in this approved experiment")
        result = run_trial(task_key)
        trials.append(result)
        return result

    trial.__name__ = "run_trial"

    @tool()
    def read_log(run_id: str, stream: str = "stderr", tail: int = 60) -> str:
        """Read stdout/stderr for a run belonging to this workspace."""
        if Path(run_id).name != run_id or stream not in ("stdout", "stderr") or not 1 <= tail <= 60:
            raise ValueError("Invalid run/log request")
        return "\n".join(ctx.executor.logs(run_id, stream, 0).text.splitlines()[-tail:])

    try:
        if ctx.budget.check().exhausted:
            raise ValueError("Budget exhausted before coder session")
        # Share gateway accounting/permissions but never replace the engine's backend.
        gateway = copy(ctx.llm)
        gateway.backend = _BudgetCheckedBackend(ctx.llm.backend, ctx.budget)
        schema = ctx.root / "src/config_schema.json"
        method_source = None
        if experiment.method.isidentifier():
            method_path = f"src/methods/{experiment.method}.py"
            if resolve(method_path).is_file():
                method_source = {"path": method_path, "content": read_file(method_path)}
        context = {
            "task": task.model_dump(),
            "experiment": experiment.model_dump(),
            "error": error,
            "tree": list_files("src"),
            "schema": json.loads(schema.read_text(encoding="utf-8")) if schema.exists() else None,
            "entrypoint_source": read_file("src/run.py"),
            "method_source": method_source,
            "trial_task_keys": [
                key for key, entry in entries.items()
                if entry["experiment_id"] == experiment.id and entry["trial"]
            ],
            "semantic_keys": task.semantic_keys,
            "protected_files": task.protected_files,
        }
        response = gateway.tool_loop(
            role="exp.coder",
            prompt_id="experiment/coder",
            tier="strong",
            max_turns=15,
            variables={"context_document": ctx.llm.wrap_untrusted(dumps(context), "coder_inputs")},
            tools=[list_files, read_file, write_file, replace_in_file, trial, read_log],
            finish_schema=CoderReport,
        )
        report = response.final
        commit("Coder candidate", author="agent:experiment")
        problems = semantic_guard(ctx, task, entries, before, report)
        if not report.ok:
            problems.append("Coder reported failure")
        if report.trial_run_id and not any(t["run_id"] == report.trial_run_id for t in trials):
            problems.append("Reported trial does not belong to this coding session")
        if problems:
            dispatch(lambda: restore(ctx, before))
            return {"ok": False, "report": report.model_dump(), "problems": problems, "trials": trials}
        # A successful same-commit trial is still enforced by the stage even if
        # the coder finishes without using run_trial.
        return {"ok": True, "report": report.model_dump(), "changed_files": sorted(changed), "trials": trials}
    except Exception as exc:
        try:
            try:
                commit("Failed coder candidate", author="agent:experiment")
            finally:
                dispatch(lambda: restore(ctx, before))
        except Exception as cleanup_error:
            # An abandoned dispatch queue must not also discard the rollback.
            raise CoderRollbackRequired(before, exc) from cleanup_error
        raise


def source_hashes(root):
    return {
        p.relative_to(root / "src").as_posix(): sha256_bytes(p.read_bytes())
        for p in (root / "src").rglob("*")
        if p.is_file() and "__pycache__" not in p.parts
    }


def preflight(ctx):
    python = ctx.executor.python
    code = """import ast,importlib.util,json,sys
from pathlib import Path
root=Path(sys.argv[1]); local={p.stem for p in root.iterdir() if p.suffix=='.py' or p.is_dir()}
imports=set(); checked=[]
for path in root.rglob('*.py'):
    text=path.read_text(encoding='utf-8'); compile(text,str(path),'exec')
    tree=ast.parse(text); checked.append(str(path.relative_to(root)))
    for node in ast.walk(tree):
        if isinstance(node,ast.Import): imports.update(a.name.split('.')[0] for a in node.names)
        elif isinstance(node,ast.ImportFrom) and not node.level and node.module: imports.add(node.module.split('.')[0])
missing=[]
for name in sorted(imports-local):
    try:
        if importlib.util.find_spec(name) is None: missing.append(name)
    except (ImportError,ValueError,ModuleNotFoundError): missing.append(name)
print(json.dumps({'files':checked,'imports':sorted(imports),'missing':missing}))
sys.exit(2 if missing else 0)
"""
    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}
    check = subprocess.run(
        [python, "-c", code, str(ctx.root / "src")],
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=45,
        env=env,
    )
    if check.returncode:
        raise ValueError(f"Static/dependency preflight failed: {check.stdout[-3000:]} {check.stderr[-2000:]}")
    result = json.loads(check.stdout)
    ruff = shutil.which("ruff", path=str(Path(python).parent) + os.pathsep + os.environ.get("PATH", ""))
    if not ruff:
        raise ValueError("Ruff is required for static checks; install the project's dev dependencies explicitly")
    lint = subprocess.run(
        [ruff, "check", "--no-cache", "--select", "F", str(ctx.root / "src")],
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=30,
        env=env,
    )
    if lint.returncode:
        raise ValueError(f"Ruff preflight failed: {lint.stdout[-3000:]} {lint.stderr[-1000:]}")
    result.update(python=python, syntax="passed", undefined_names="passed", dependencies="passed")
    ctx.archive.put("environments/preflight.json", "other", dumps(result), producer="agent:experiment/preflight")
